drop function if exists public.dkd_safe_uuid_text_to_uuid_dkd(text);
create function public.dkd_safe_uuid_text_to_uuid_dkd(dkd_param_user_id_text text)
returns uuid
language plpgsql
immutable
as $$
begin
  if coalesce(trim(dkd_param_user_id_text), '') ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$' then
    return trim(dkd_param_user_id_text)::uuid;
  end if;
  return null;
exception
  when others then
    return null;
end;
$$;

