create or replace function public.dkd_send_support_thread_message(dkd_param_thread_id uuid, dkd_param_message_text text)
returns jsonb
language plpgsql
security definer
set search_path to 'public'
as $function$
declare
  dkd_var_auth_user_id uuid := auth.uid();
  dkd_var_is_admin boolean := coalesce(public.dkd_is_admin(), false);
  dkd_var_thread_record public.dkd_support_threads%rowtype;
  dkd_var_clean_message_text text;
  dkd_var_sender_key text;
  dkd_var_sender_title text;
  dkd_var_message_owner_id uuid;
  dkd_var_next_status_key text;
  dkd_var_next_status_title text;
  dkd_var_message_id uuid;
begin
  if dkd_var_auth_user_id is null then raise exception 'dkd_auth_required'; end if;
  dkd_var_clean_message_text := trim(coalesce(dkd_param_message_text, ''));
  if length(dkd_var_clean_message_text) < 1 then raise exception 'dkd_support_message_too_short'; end if;
  select t.* into dkd_var_thread_record from public.dkd_support_threads t where t.dkd_id=dkd_param_thread_id and (t.dkd_user_id=dkd_var_auth_user_id or dkd_var_is_admin) limit 1;
  if not found then raise exception 'dkd_support_thread_not_found'; end if;
  if dkd_var_is_admin then
    dkd_var_sender_key:='dkd_admin'; dkd_var_sender_title:='DrabornEagle • Admin'; dkd_var_message_owner_id:=dkd_var_thread_record.dkd_user_id;
    dkd_var_next_status_key:='dkd_answered'; dkd_var_next_status_title:='DrabornEagle yanıtladı';
  else
    dkd_var_sender_key:='dkd_customer'; dkd_var_sender_title:='Kullanıcı'; dkd_var_message_owner_id:=dkd_var_auth_user_id;
    dkd_var_next_status_key:='dkd_open'; dkd_var_next_status_title:='Yeni kullanıcı mesajı';
  end if;
  insert into public.dkd_support_messages(dkd_thread_id,dkd_user_id,dkd_sender_key,dkd_sender_title,dkd_message_text)
  values(dkd_var_thread_record.dkd_id,dkd_var_message_owner_id,dkd_var_sender_key,dkd_var_sender_title,dkd_var_clean_message_text)
  returning dkd_id into dkd_var_message_id;
  update public.dkd_support_threads set dkd_status_key=dkd_var_next_status_key,dkd_status_title=dkd_var_next_status_title,
    dkd_needs_admin_reply=not dkd_var_is_admin, dkd_admin_needed=not dkd_var_is_admin,
    dkd_last_message_text=left(dkd_var_clean_message_text,240),dkd_updated_at=now()
  where dkd_id=dkd_var_thread_record.dkd_id;
  return jsonb_build_object('dkd_ok',true,'dkd_thread_id',dkd_var_thread_record.dkd_id,'dkd_message_id',dkd_var_message_id,'dkd_sender_key',dkd_var_sender_key,'dkd_sender_title',dkd_var_sender_title);
end;
$function$;

-- Admin user search/detail/edit/delete.
create or replace function public.dkd_admin_user_search_dkd(dkd_param_search text default '', dkd_param_limit integer default 50)
returns jsonb
language plpgsql
stable
security definer
set search_path to 'public','auth'
as $function$
declare dkd_result jsonb;
begin
  if not public.dkd_is_admin() then raise exception 'dkd_admin_required'; end if;
  select coalesce(jsonb_agg(to_jsonb(x) order by x.dkd_created_at desc),'[]'::jsonb) into dkd_result
  from (
    select u.id as dkd_user_id,u.email as dkd_email,u.phone as dkd_phone,u.created_at as dkd_created_at,u.last_sign_in_at as dkd_last_sign_in_at,
           p.nickname as dkd_nickname,p.dbg_id as dkd_dbg_id,p.avatar_image_url as dkd_avatar_image_url,p.courier_status as dkd_courier_status,p.dkd_city,p.dkd_region,
           p.courier_vehicle_type,p.courier_completed_jobs,p.dkd_courier_online,
           exists(select 1 from public.dkd_admin_users a where a.user_id=u.id) as dkd_is_admin
    from auth.users u
    left join public.dkd_profiles p on p.user_id=u.id
    where trim(coalesce(dkd_param_search,''))=''
       or u.id::text ilike '%'||trim(dkd_param_search)||'%'
       or coalesce(u.email,'') ilike '%'||trim(dkd_param_search)||'%'
       or coalesce(u.phone,'') ilike '%'||trim(dkd_param_search)||'%'
       or coalesce(p.nickname,'') ilike '%'||trim(dkd_param_search)||'%'
       or coalesce(p.dbg_id,'') ilike '%'||trim(dkd_param_search)||'%'
    order by u.created_at desc
    limit least(greatest(coalesce(dkd_param_limit,50),1),150)
  ) x;
  return dkd_result;
end;
$function$;

create or replace function public.dkd_admin_user_detail_dkd(dkd_param_user_id uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path to 'public','auth'
as $function$
declare dkd_result jsonb; dkd_earnings jsonb;
begin
  if not public.dkd_is_admin() then raise exception 'dkd_admin_required'; end if;
  select jsonb_build_object(
    'dkd_user_id',u.id,'dkd_email',u.email,'dkd_phone',u.phone,'dkd_created_at',u.created_at,'dkd_updated_at',u.updated_at,'dkd_last_sign_in_at',u.last_sign_in_at,
    'dkd_email_confirmed_at',u.email_confirmed_at,'dkd_phone_confirmed_at',u.phone_confirmed_at,'dkd_raw_user_meta_data',u.raw_user_meta_data,
    'dkd_profile',coalesce(to_jsonb(p),'{}'::jsonb),
    'dkd_is_admin',exists(select 1 from public.dkd_admin_users ad where ad.user_id=u.id)
  ) into dkd_result
  from auth.users u left join public.dkd_profiles p on p.user_id=u.id where u.id=dkd_param_user_id;
  if dkd_result is null then raise exception 'dkd_user_not_found'; end if;
  dkd_earnings := public.dkd_courier_earnings_summary_dkd(dkd_param_user_id);
  return dkd_result || jsonb_build_object('dkd_earnings',dkd_earnings);
