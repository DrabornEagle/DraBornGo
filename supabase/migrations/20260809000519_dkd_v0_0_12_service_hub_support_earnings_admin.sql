$function$;

create or replace function public.dkd_support_admin_threads_dkd(dkd_param_search text default '', dkd_param_limit integer default 80)
returns jsonb
language plpgsql
stable
security definer
set search_path to 'public','auth'
as $function$
declare dkd_result jsonb;
begin
  if not public.dkd_is_admin() then raise exception 'dkd_admin_required'; end if;
  select coalesce(jsonb_agg(to_jsonb(x) order by x.dkd_updated_at desc),'[]'::jsonb) into dkd_result
  from (
    select t.dkd_id as dkd_thread_id,t.dkd_user_id,t.dkd_ticket_code,t.dkd_status_key,t.dkd_status_title,t.dkd_last_message_text,t.dkd_created_at,t.dkd_updated_at,
