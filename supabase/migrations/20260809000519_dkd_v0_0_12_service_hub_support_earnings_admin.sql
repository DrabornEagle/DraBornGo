    from public.dkd_support_threads t
    left join public.dkd_profiles p on p.user_id=t.dkd_user_id
    left join auth.users u on u.id=t.dkd_user_id
    where t.dkd_topic_key='dkd_direct_admin'
      and (trim(coalesce(dkd_param_search,''))='' or coalesce(p.nickname,'') ilike '%'||trim(dkd_param_search)||'%' or coalesce(u.email,'') ilike '%'||trim(dkd_param_search)||'%' or coalesce(p.dbg_id,'') ilike '%'||trim(dkd_param_search)||'%')
    order by t.dkd_updated_at desc
    limit least(greatest(coalesce(dkd_param_limit,80),1),200)
  ) x;
  return dkd_result;
end;
$function$;

