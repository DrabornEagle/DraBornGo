create or replace function public.dkd_courier_job_customer_user_id_dkd(dkd_param_job_id bigint)
returns uuid
language plpgsql
security definer
set search_path to 'public'
as $function$
declare
  dkd_job_row public.dkd_courier_jobs%rowtype;
  dkd_target_user_id_value uuid;
begin
  if dkd_param_job_id is null or dkd_param_job_id <= 0 then return null; end if;
  select * into dkd_job_row from public.dkd_courier_jobs where id = dkd_param_job_id limit 1;
  if not found then return null; end if;
  dkd_target_user_id_value := dkd_job_row.customer_user_id;
  if dkd_target_user_id_value is null and dkd_job_row.cargo_shipment_id is not null then
    select customer_user_id into dkd_target_user_id_value
    from public.dkd_cargo_shipments
    where id = dkd_job_row.cargo_shipment_id
    limit 1;
  end if;
  if dkd_target_user_id_value is not null and dkd_job_row.customer_user_id is null then
    update public.dkd_courier_jobs
       set customer_user_id = dkd_target_user_id_value,
           cargo_meta = coalesce(cargo_meta,'{}'::jsonb) || jsonb_build_object('dkd_customer_user_id',dkd_target_user_id_value::text),
           updated_at = now()
     where id = dkd_param_job_id;
  end if;
  return dkd_target_user_id_value;
end;
$function$;

-- Courier online work sessions and earnings analytics.
create table if not exists public.dkd_courier_online_sessions (
  dkd_id bigint generated by default as identity primary key,
  dkd_user_id uuid not null,
  dkd_started_at timestamptz not null default now(),
  dkd_ended_at timestamptz,
  dkd_duration_seconds bigint,
  dkd_country text,
  dkd_city text,
  dkd_region text,
  dkd_created_at timestamptz not null default now(),
  constraint dkd_courier_online_sessions_duration_check check (dkd_duration_seconds is null or dkd_duration_seconds >= 0)
);
create index if not exists dkd_courier_online_sessions_user_started_idx on public.dkd_courier_online_sessions(dkd_user_id, dkd_started_at desc);
create unique index if not exists dkd_courier_online_sessions_one_open_idx on public.dkd_courier_online_sessions(dkd_user_id) where dkd_ended_at is null;
alter table public.dkd_courier_online_sessions enable row level security;
drop policy if exists dkd_courier_online_sessions_self_select on public.dkd_courier_online_sessions;
create policy dkd_courier_online_sessions_self_select on public.dkd_courier_online_sessions for select to authenticated using (dkd_user_id = auth.uid() or public.dkd_is_admin());

insert into public.dkd_courier_online_sessions(dkd_user_id, dkd_started_at, dkd_country, dkd_city, dkd_region)
select p.user_id, coalesce(p.dkd_courier_last_online_at, now()), p.dkd_courier_online_country, p.dkd_courier_online_city, p.dkd_courier_online_region
from public.dkd_profiles p
where p.dkd_courier_online is true
  and not exists (select 1 from public.dkd_courier_online_sessions s where s.dkd_user_id=p.user_id and s.dkd_ended_at is null)
on conflict do nothing;

create or replace function public.dkd_close_courier_online_session_dkd(dkd_param_user_id uuid)
returns void
language plpgsql
security definer
set search_path to 'public'
as $function$
begin
  update public.dkd_courier_online_sessions
     set dkd_ended_at = now(),
         dkd_duration_seconds = greatest(0, floor(extract(epoch from (now() - dkd_started_at)))::bigint)
   where dkd_user_id = dkd_param_user_id
     and dkd_ended_at is null;
end;
$function$;

create or replace function public.dkd_courier_online_set_dkd(
  dkd_param_online boolean,
  dkd_param_country text default 'Türkiye',
  dkd_param_city text default 'Ankara',
  dkd_param_region text default '',
  dkd_param_live_lat numeric default null,
  dkd_param_live_lng numeric default null
)
returns jsonb
language plpgsql
security definer
set search_path to 'public','auth'
as $function$
declare
  dkd_user_id_value uuid := auth.uid();
  dkd_next_job_id_value bigint := null;
  dkd_active_delivery_job_id_value bigint := null;
  dkd_existing_offer_job_id_value bigint := null;
  dkd_safe_country_value text := coalesce(nullif(trim(dkd_param_country), ''), 'Türkiye');
  dkd_safe_city_value text := coalesce(nullif(trim(dkd_param_city), ''), 'Ankara');
  dkd_safe_region_value text := coalesce(nullif(trim(dkd_param_region), ''), '');
begin
  if dkd_user_id_value is null then
    return jsonb_build_object('dkd_ok_value', false, 'dkd_reason_value', 'auth_required');
  end if;
  insert into public.dkd_profiles (user_id) values (dkd_user_id_value) on conflict (user_id) do nothing;
  select j.id into dkd_active_delivery_job_id_value
  from public.dkd_courier_jobs j
  where j.assigned_user_id = dkd_user_id_value
    and coalesce(j.is_active, true) = true
    and lower(coalesce(j.status, '')) in ('accepted','assigned','to_pickup','picked_up','to_customer','delivering')
    and lower(coalesce(j.pickup_status, '')) not in ('delivered','cancelled','canceled')
  order by j.updated_at desc nulls last, j.created_at desc nulls last
  limit 1;
  if dkd_active_delivery_job_id_value is not null then
    perform public.dkd_close_courier_online_session_dkd(dkd_user_id_value);
    update public.dkd_profiles
       set dkd_courier_online=false,
           dkd_courier_auto_assigned_job_id=dkd_active_delivery_job_id_value,
           dkd_courier_last_online_at=now()
     where user_id=dkd_user_id_value;
    return jsonb_build_object('dkd_ok_value',true,'dkd_online_value',false,'dkd_has_active_delivery_value',true,'dkd_assigned_job_id',dkd_active_delivery_job_id_value,'assigned_job_id',dkd_active_delivery_job_id_value);
  end if;
  if dkd_param_online is not true then
    perform public.dkd_close_courier_online_session_dkd(dkd_user_id_value);
    update public.dkd_profiles
       set dkd_courier_online=false, dkd_courier_auto_assigned_job_id=null, dkd_courier_last_online_at=now()
     where user_id=dkd_user_id_value;
    return jsonb_build_object('dkd_ok_value',true,'dkd_online_value',false,'dkd_assigned_job_id',null,'assigned_job_id',null);
  end if;
  if not exists (select 1 from public.dkd_profiles p where p.user_id=dkd_user_id_value and coalesce(p.courier_status,'')='approved') then
    return jsonb_build_object('dkd_ok_value',false,'dkd_reason_value','courier_not_approved');
  end if;
  insert into public.dkd_courier_online_sessions(dkd_user_id,dkd_started_at,dkd_country,dkd_city,dkd_region)
  values(dkd_user_id_value,now(),dkd_safe_country_value,dkd_safe_city_value,dkd_safe_region_value)
  on conflict do nothing;
  update public.dkd_profiles
     set dkd_courier_online=true,
         dkd_courier_online_country=dkd_safe_country_value,
         dkd_courier_online_city=dkd_safe_city_value,
         dkd_courier_online_region=dkd_safe_region_value,
         dkd_courier_online_lat=dkd_param_live_lat,
         dkd_courier_online_lng=dkd_param_live_lng,
         dkd_courier_last_online_at=now()
   where user_id=dkd_user_id_value;
  select j.id into dkd_existing_offer_job_id_value
  from public.dkd_courier_jobs j
  where j.assigned_user_id=dkd_user_id_value
    and coalesce(j.is_active,true)=true
    and lower(coalesce(j.status,'')) in ('dkd_auto_assigned','dkd_assigned_offer','courier_offer','auto_assigned','assigned_offer')
  order by j.updated_at desc nulls last, j.created_at desc nulls last limit 1;
  if dkd_existing_offer_job_id_value is not null then
    update public.dkd_profiles set dkd_courier_auto_assigned_job_id=dkd_existing_offer_job_id_value where user_id=dkd_user_id_value;
    return jsonb_build_object('dkd_ok_value',true,'dkd_online_value',true,'dkd_assigned_job_id',dkd_existing_offer_job_id_value,'assigned_job_id',dkd_existing_offer_job_id_value);
  end if;
  select j.id into dkd_next_job_id_value
  from public.dkd_courier_jobs j
  where j.assigned_user_id is null
    and coalesce(j.is_active,true)=true
    and lower(coalesce(j.status,'open')) in ('open','ready','published')
    and not public.dkd_jsonb_array_has_text_dkd(coalesce(j.cargo_meta,'{}'::jsonb)->'dkd_rejected_courier_user_ids',dkd_user_id_value::text)
    and public.dkd_region_match_dkd(j.dkd_country,j.dkd_city,j.dkd_region,dkd_safe_country_value,dkd_safe_city_value,dkd_safe_region_value)
  order by case when dkd_param_live_lat is not null and dkd_param_live_lng is not null and j.pickup_lat is not null and j.pickup_lng is not null then public.dkd_distance_km_between(dkd_param_live_lat,dkd_param_live_lng,j.pickup_lat,j.pickup_lng) else null end asc nulls last,
           j.updated_at desc nulls last, j.created_at desc
  limit 1 for update skip locked;
  if dkd_next_job_id_value is not null then
    update public.dkd_courier_jobs j
       set assigned_user_id=dkd_user_id_value,
           status='dkd_assigned_offer',
           dkd_auto_assigned_at=now(),
           dkd_assignment_expires_at=now()+interval '4 minutes',
           cargo_meta=coalesce(j.cargo_meta,'{}'::jsonb)||jsonb_build_object('dkd_auto_assigned_to',dkd_user_id_value::text,'dkd_auto_assigned_at',now()),
           updated_at=now()
     where j.id=dkd_next_job_id_value;
  end if;
  update public.dkd_profiles set dkd_courier_auto_assigned_job_id=dkd_next_job_id_value where user_id=dkd_user_id_value;
  return jsonb_build_object('dkd_ok_value',true,'dkd_online_value',true,'dkd_has_active_delivery_value',false,'dkd_assigned_job_id',dkd_next_job_id_value,'assigned_job_id',dkd_next_job_id_value);
end;
$function$;

create or replace function public.dkd_courier_earnings_summary_dkd(dkd_param_user_id uuid default null)
returns jsonb
language plpgsql
stable
security definer
set search_path to 'public','auth'
as $function$
declare
  dkd_auth_user_id uuid := auth.uid();
  dkd_target_user_id uuid := coalesce(dkd_param_user_id, auth.uid());
  dkd_is_admin_value boolean := coalesce(public.dkd_is_admin(),false);
  dkd_day_start timestamptz := (date_trunc('day', now() at time zone 'Europe/Istanbul') at time zone 'Europe/Istanbul');
  dkd_week_start timestamptz := (date_trunc('week', now() at time zone 'Europe/Istanbul') at time zone 'Europe/Istanbul');
  dkd_month_start timestamptz := (date_trunc('month', now() at time zone 'Europe/Istanbul') at time zone 'Europe/Istanbul');
  dkd_result jsonb;
begin
  if dkd_auth_user_id is null or dkd_target_user_id is null then raise exception 'dkd_auth_required'; end if;
  if dkd_target_user_id <> dkd_auth_user_id and not dkd_is_admin_value then raise exception 'dkd_admin_required'; end if;
  with periods as (
    select 'daily'::text as key, dkd_day_start as start_at, now() as end_at
    union all select 'weekly', dkd_week_start, now()
    union all select 'monthly', dkd_month_start, now()
  ), stats as (
    select p.key,
      coalesce((select sum(coalesce(j.fee_tl,0)) from public.dkd_courier_jobs j where j.assigned_user_id=dkd_target_user_id and coalesce(j.completed_at,j.updated_at)>=p.start_at and coalesce(j.completed_at,j.updated_at)<=p.end_at and (j.completed_at is not null or lower(coalesce(j.status,'')) in ('completed','delivered'))),0)::numeric as earnings_tl,
      coalesce((select count(*) from public.dkd_courier_jobs j where j.assigned_user_id=dkd_target_user_id and coalesce(j.completed_at,j.updated_at)>=p.start_at and coalesce(j.completed_at,j.updated_at)<=p.end_at and (j.completed_at is not null or lower(coalesce(j.status,'')) in ('completed','delivered'))),0)::bigint as completed_jobs,
      coalesce((select sum(greatest(0,extract(epoch from (least(coalesce(s.dkd_ended_at,now()),p.end_at)-greatest(s.dkd_started_at,p.start_at))))) from public.dkd_courier_online_sessions s where s.dkd_user_id=dkd_target_user_id and s.dkd_started_at < p.end_at and coalesce(s.dkd_ended_at,now()) > p.start_at),0)::numeric as online_seconds
    from periods p
  )
  select jsonb_object_agg(key,jsonb_build_object(
    'dkd_earnings_tl',round(earnings_tl,2),
    'dkd_completed_jobs',completed_jobs,
    'dkd_online_seconds',floor(online_seconds),
    'dkd_online_hours',round(online_seconds/3600.0,2),
    'dkd_hourly_tl',case when online_seconds>0 then round(earnings_tl/(online_seconds/3600.0),2) else 0 end
  )) into dkd_result from stats;
  return coalesce(dkd_result,'{}'::jsonb) || jsonb_build_object(
    'dkd_user_id',dkd_target_user_id,
    'dkd_generated_at',now(),
    'dkd_is_online',coalesce((select p.dkd_courier_online from public.dkd_profiles p where p.user_id=dkd_target_user_id),false),
    'dkd_lifetime_earnings_tl',coalesce((select round(sum(coalesce(j.fee_tl,0)),2) from public.dkd_courier_jobs j where j.assigned_user_id=dkd_target_user_id and (j.completed_at is not null or lower(coalesce(j.status,'')) in ('completed','delivered'))),0),
    'dkd_lifetime_completed_jobs',coalesce((select count(*) from public.dkd_courier_jobs j where j.assigned_user_id=dkd_target_user_id and (j.completed_at is not null or lower(coalesce(j.status,'')) in ('completed','delivered'))),0)
  );
end;
$function$;

grant execute on function public.dkd_courier_earnings_summary_dkd(uuid) to authenticated;

