create or replace function public.dkd_support_thread_messages_dkd(dkd_param_thread_id uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path to 'public','auth'
as $function$
declare
  dkd_user_id_value uuid := auth.uid();
  dkd_is_admin_value boolean := coalesce(public.dkd_is_admin(),false);
  dkd_owner_value uuid;
  dkd_result jsonb;
