drop function if exists public.dkd_source_user_id_by_column_dkd(text, text, text);
create function public.dkd_source_user_id_by_column_dkd(
  dkd_param_table_name text,
  dkd_param_column_name text,
  dkd_param_filter_value text
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  dkd_source_json_value jsonb := '{}'::jsonb;
  dkd_candidate_user_id_text_value text := '';
begin
  if coalesce(trim(dkd_param_table_name), '') = ''
     or coalesce(trim(dkd_param_column_name), '') = ''
     or coalesce(trim(dkd_param_filter_value), '') = '' then
    return null;
  end if;

  if not exists (
    select 1
      from information_schema.tables dkd_table_scope
     where dkd_table_scope.table_schema = 'public'
       and dkd_table_scope.table_name = dkd_param_table_name
  ) then
    return null;
  end if;

  if not exists (
    select 1
      from information_schema.columns dkd_column_scope
     where dkd_column_scope.table_schema = 'public'
       and dkd_column_scope.table_name = dkd_param_table_name
       and dkd_column_scope.column_name = dkd_param_column_name
  ) then
    return null;
  end if;

  execute format(
    'select to_jsonb(dkd_source_scope) from public.%I dkd_source_scope where dkd_source_scope.%I::text = $1 limit 1',
    dkd_param_table_name,
    dkd_param_column_name
  ) into dkd_source_json_value using dkd_param_filter_value;

  dkd_candidate_user_id_text_value := coalesce(public.dkd_json_user_id_text_dkd(coalesce(dkd_source_json_value, '{}'::jsonb)), '');
  return public.dkd_safe_uuid_text_to_uuid_dkd(dkd_candidate_user_id_text_value);
exception
  when others then
    return null;
end;
$$;

revoke all on function public.dkd_source_user_id_by_column_dkd(text, text, text) from public;
grant execute on function public.dkd_source_user_id_by_column_dkd(text, text, text) to authenticated, service_role;

drop function if exists public.dkd_courier_job_customer_user_id_dkd(bigint);
create function public.dkd_courier_job_customer_user_id_dkd(dkd_param_job_id bigint)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  dkd_job_json_value jsonb := '{}'::jsonb;
  dkd_meta_value jsonb := '{}'::jsonb;
  dkd_candidate_user_id_text_value text := '';
  dkd_cargo_shipment_id_text_value text := '';
  dkd_order_id_text_value text := '';
  dkd_target_user_id_value uuid := null;
  dkd_table_name_value text := '';
  dkd_column_name_value text := '';
begin
  if dkd_param_job_id is null or dkd_param_job_id <= 0 then
    return null;
  end if;

  if to_regclass('public.dkd_courier_jobs') is null then
    return null;
  end if;

  select to_jsonb(dkd_job_scope)
    into dkd_job_json_value
    from public.dkd_courier_jobs dkd_job_scope
   where dkd_job_scope.id = dkd_param_job_id
   limit 1;

  if dkd_job_json_value is null or dkd_job_json_value = '{}'::jsonb then
    return null;
  end if;

  dkd_meta_value := case
    when jsonb_typeof(coalesce(dkd_job_json_value->'cargo_meta', '{}'::jsonb)) = 'object' then coalesce(dkd_job_json_value->'cargo_meta', '{}'::jsonb)
    else '{}'::jsonb
  end;

  dkd_candidate_user_id_text_value := coalesce(
    public.dkd_json_user_id_text_dkd(dkd_job_json_value),
    public.dkd_json_user_id_text_dkd(dkd_meta_value),
    public.dkd_json_user_id_text_dkd(coalesce(dkd_meta_value->'dkd_original_order', '{}'::jsonb)),
    ''
  );
  dkd_target_user_id_value := public.dkd_safe_uuid_text_to_uuid_dkd(dkd_candidate_user_id_text_value);

  dkd_cargo_shipment_id_text_value := coalesce(
    nullif(dkd_job_json_value->>'cargo_shipment_id', ''),
    nullif(dkd_meta_value->>'dkd_cargo_shipment_id', ''),
    nullif(dkd_meta_value->>'cargo_shipment_id', ''),
    ''
  );

  if dkd_target_user_id_value is null and dkd_cargo_shipment_id_text_value <> '' then
    dkd_target_user_id_value := public.dkd_source_user_id_by_column_dkd('dkd_cargo_shipments', 'id', dkd_cargo_shipment_id_text_value);
  end if;

  if dkd_target_user_id_value is null then
    dkd_target_user_id_value := public.dkd_source_user_id_by_column_dkd('dkd_cargo_shipments', 'courier_job_id', dkd_param_job_id::text);
  end if;

  dkd_order_id_text_value := coalesce(
    nullif(dkd_job_json_value->>'order_id', ''),
    nullif(dkd_meta_value->>'dkd_restaurant_order_id', ''),
    nullif(dkd_meta_value->>'dkd_business_product_order_id', ''),
    nullif(dkd_meta_value->>'dkd_order_id', ''),
    nullif(dkd_meta_value->>'order_id', ''),
    nullif(dkd_meta_value->>'dkd_service_network_source_id', ''),
    nullif(dkd_meta_value->>'dkd_source_id', ''),
    nullif(dkd_meta_value->'dkd_original_order'->>'id', ''),
    nullif(dkd_meta_value->'dkd_original_order'->>'dkd_order_id', ''),
    ''
  );

  if dkd_target_user_id_value is null and dkd_order_id_text_value <> '' then
    foreach dkd_table_name_value in array array[
      'dkd_service_network_restaurant_orders',
      'dkd_service_network_requests',
      'dkd_business_product_orders',
      'dkd_cargo_shipments'
    ] loop
      foreach dkd_column_name_value in array array['id', 'dkd_order_id', 'order_id', 'dkd_source_id', 'request_id'] loop
        dkd_target_user_id_value := public.dkd_source_user_id_by_column_dkd(dkd_table_name_value, dkd_column_name_value, dkd_order_id_text_value);
        exit when dkd_target_user_id_value is not null;
      end loop;
      exit when dkd_target_user_id_value is not null;
    end loop;
  end if;

  if dkd_target_user_id_value is null then
    foreach dkd_table_name_value in array array[
      'dkd_service_network_restaurant_orders',
      'dkd_service_network_requests',
      'dkd_business_product_orders',
      'dkd_cargo_shipments'
    ] loop
      foreach dkd_column_name_value in array array['courier_job_id', 'dkd_courier_job_id', 'dkd_job_id'] loop
        dkd_target_user_id_value := public.dkd_source_user_id_by_column_dkd(dkd_table_name_value, dkd_column_name_value, dkd_param_job_id::text);
        exit when dkd_target_user_id_value is not null;
      end loop;
      exit when dkd_target_user_id_value is not null;
    end loop;
  end if;

  if dkd_target_user_id_value is not null then
    begin
      update public.dkd_courier_jobs dkd_job_scope
         set customer_user_id = coalesce(dkd_job_scope.customer_user_id, dkd_target_user_id_value),
             cargo_meta = coalesce(dkd_job_scope.cargo_meta, '{}'::jsonb) || jsonb_build_object('dkd_customer_user_id', dkd_target_user_id_value::text),
             updated_at = now()
       where dkd_job_scope.id = dkd_param_job_id;
    exception
      when others then
        null;
    end;
  end if;

  return dkd_target_user_id_value;
end;
$$;

revoke all on function public.dkd_courier_job_customer_user_id_dkd(bigint) from public;
grant execute on function public.dkd_courier_job_customer_user_id_dkd(bigint) to authenticated, service_role;

drop function if exists public.dkd_customer_status_target_tokens_dkd(uuid);
create function public.dkd_customer_status_target_tokens_dkd(dkd_param_user_id uuid)
returns table (
  user_id uuid,
  expo_push_token text,
  token text,
  dkd_expo_push_token text,
  dkd_push_segment text
)
language sql
security definer
set search_path = public
as $$
  select distinct on (coalesce(dkd_token_scope.expo_push_token, to_jsonb(dkd_token_scope)->>'token'))
    dkd_token_scope.user_id,
    coalesce(dkd_token_scope.expo_push_token, to_jsonb(dkd_token_scope)->>'token') as expo_push_token,
    coalesce(dkd_token_scope.expo_push_token, to_jsonb(dkd_token_scope)->>'token') as token,
    coalesce(dkd_token_scope.expo_push_token, to_jsonb(dkd_token_scope)->>'token') as dkd_expo_push_token,
    'customer_status'::text as dkd_push_segment
  from public.dkd_push_tokens dkd_token_scope
  where dkd_token_scope.user_id = dkd_param_user_id
    and coalesce(dkd_token_scope.is_active, false) is true
    and coalesce(dkd_token_scope.expo_push_token, to_jsonb(dkd_token_scope)->>'token', '') like 'ExponentPushToken%'
  order by coalesce(dkd_token_scope.expo_push_token, to_jsonb(dkd_token_scope)->>'token'), dkd_token_scope.updated_at desc nulls last;
$$;

