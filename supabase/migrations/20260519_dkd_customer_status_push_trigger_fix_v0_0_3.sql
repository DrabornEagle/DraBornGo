drop function if exists public.dkd_courier_job_status_push_after_update_dkd();
create function public.dkd_courier_job_status_push_after_update_dkd()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  dkd_old_status_value text := lower(coalesce(old.status, ''));
  dkd_new_status_value text := lower(coalesce(new.status, ''));
  dkd_old_pickup_status_value text := lower(coalesce(old.pickup_status, ''));
  dkd_new_pickup_status_value text := lower(coalesce(new.pickup_status, ''));
  dkd_event_key_value text := '';
begin
  if new.id is null or coalesce(new.is_active, true) is not true then
    return new;
  end if;

  if dkd_old_status_value not in ('completed', 'delivered', 'done', 'finished')
     and (dkd_new_status_value in ('completed', 'delivered', 'done', 'finished') or dkd_new_pickup_status_value = 'delivered') then
    dkd_event_key_value := 'courier_job_delivered';
  elsif dkd_old_status_value not in ('picked_up', 'to_customer', 'delivering')
     and dkd_old_pickup_status_value not in ('picked_up', 'delivered')
     and (dkd_new_status_value in ('picked_up', 'to_customer', 'delivering') or dkd_new_pickup_status_value = 'picked_up') then
    dkd_event_key_value := 'courier_job_picked_up';
  elsif dkd_old_status_value not in ('accepted', 'assigned', 'to_business')
     and (
       dkd_new_status_value in ('accepted', 'assigned', 'to_business')
       or (old.assigned_user_id is distinct from new.assigned_user_id and new.assigned_user_id is not null)
     ) then
    dkd_event_key_value := 'courier_job_accepted';
  end if;

  if dkd_event_key_value <> '' then
    perform public.dkd_courier_job_emit_customer_status_push_dkd(new.id, dkd_event_key_value);
  end if;

  return new;
exception
  when others then
    return new;
end;
$$;

