create or replace function public.dkd_social_admin_update_report_status(
  dkd_param_report_id bigint,
  dkd_param_status_key text,
  dkd_param_admin_note_text text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  dkd_current_admin_user_id uuid := auth.uid();
  dkd_clean_status_key text := coalesce(nullif(trim(dkd_param_status_key), ''), 'dkd_reviewing');
  dkd_updated_count integer := 0;
begin
  if coalesce(public.dkd_is_admin(), false) is not true then
    return jsonb_build_object('ok', false, 'reason', 'admin_required');
  end if;

  if dkd_clean_status_key not in ('dkd_open', 'dkd_reviewing', 'dkd_resolved', 'dkd_dismissed') then
    return jsonb_build_object('ok', false, 'reason', 'invalid_status');
  end if;

  update public.dkd_social_reports dkd_report_row
  set dkd_status_key = dkd_clean_status_key,
      dkd_admin_note_text = nullif(trim(coalesce(dkd_param_admin_note_text, dkd_report_row.dkd_admin_note_text, '')), ''),
      dkd_admin_user_id = dkd_current_admin_user_id,
      dkd_updated_at = now(),
      dkd_resolved_at = case when dkd_clean_status_key in ('dkd_resolved', 'dkd_dismissed') then now() else null end
  where dkd_report_row.dkd_id = dkd_param_report_id;

  get diagnostics dkd_updated_count = row_count;

  return jsonb_build_object('ok', dkd_updated_count > 0, 'reason', case when dkd_updated_count > 0 then 'updated' else 'not_found' end);
end;
$$;

