create or replace function public.dkd_social_report_user(
  dkd_param_target_user_id uuid,
  dkd_param_reason_key text default 'dkd_inappropriate_content',
  dkd_param_detail_text text default null,
  dkd_param_thread_id uuid default null,
  dkd_param_message_id bigint default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  dkd_current_user_id uuid := auth.uid();
  dkd_target_exists_value boolean := false;
  dkd_report_id_value bigint;
  dkd_clean_reason_key text := lower(regexp_replace(coalesce(nullif(trim(dkd_param_reason_key), ''), 'dkd_inappropriate_content'), '[^a-z0-9_]+', '_', 'g'));
  dkd_clean_detail_text text := nullif(trim(coalesce(dkd_param_detail_text, '')), '');
begin
  if dkd_current_user_id is null then
    return jsonb_build_object('ok', false, 'reason', 'auth_required');
  end if;

  if dkd_param_target_user_id is null then
    return jsonb_build_object('ok', false, 'reason', 'target_not_found');
  end if;

  if dkd_param_target_user_id = dkd_current_user_id then
    return jsonb_build_object('ok', false, 'reason', 'cannot_report_self');
  end if;

  if char_length(dkd_clean_reason_key) < 3 then
    dkd_clean_reason_key := 'dkd_inappropriate_content';
  end if;

  if dkd_clean_detail_text is not null and char_length(dkd_clean_detail_text) > 1200 then
    dkd_clean_detail_text := left(dkd_clean_detail_text, 1200);
  end if;

  select exists (
    select 1
    from public.dkd_profiles dkd_profile_row
    where dkd_profile_row.user_id = dkd_param_target_user_id
  ) into dkd_target_exists_value;

  if dkd_target_exists_value is not true then
    return jsonb_build_object('ok', false, 'reason', 'target_not_found');
  end if;

  insert into public.dkd_social_reports (
    dkd_reporter_user_id,
    dkd_reported_user_id,
    dkd_thread_id,
    dkd_message_id,
    dkd_reason_key,
    dkd_detail_text,
    dkd_status_key
  ) values (
    dkd_current_user_id,
    dkd_param_target_user_id,
    dkd_param_thread_id,
    dkd_param_message_id,
    dkd_clean_reason_key,
    dkd_clean_detail_text,
    'dkd_open'
  )
  returning dkd_id into dkd_report_id_value;

  return jsonb_build_object('ok', true, 'reason', 'reported', 'dkd_report_id', dkd_report_id_value);
end;
$$;

