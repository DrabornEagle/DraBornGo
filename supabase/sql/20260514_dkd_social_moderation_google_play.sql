create or replace function public.dkd_social_search_profiles(dkd_param_query text, dkd_param_limit integer default 12)
returns table (
  user_id uuid,
  ally_id bigint,
  nickname text,
  avatar_emoji text,
  level integer,
  rank_key text,
  is_friend boolean,
  pending_sent boolean,
  pending_received boolean,
  request_id bigint
)
language sql
security definer
set search_path = public
stable
as $$
  with dkd_current_user_query as (
    select
      auth.uid() as dkd_current_user_id,
      regexp_replace(coalesce(trim(dkd_param_query), ''), '[^0-9]', '', 'g') as dkd_digits_text,
      lower(coalesce(trim(dkd_param_query), '')) as dkd_query_text
  )
  select
    dkd_profile_row.user_id,
    dkd_profile_row.ally_id,
    coalesce(nullif(trim(dkd_profile_row.nickname), ''), 'Oyuncu') as nickname,
    coalesce(nullif(trim(dkd_profile_row.avatar_emoji), ''), '🦅') as avatar_emoji,
    coalesce(dkd_profile_row.level, 1) as level,
    coalesce(dkd_profile_row.rank_key, 'rookie') as rank_key,
    exists (
      select 1
      from public.dkd_friendships dkd_friendship_row
      where (dkd_friendship_row.user_low = dkd_profile_row.user_id and dkd_friendship_row.user_high = (select dkd_current_user_id from dkd_current_user_query))
         or (dkd_friendship_row.user_high = dkd_profile_row.user_id and dkd_friendship_row.user_low = (select dkd_current_user_id from dkd_current_user_query))
    ) as is_friend,
    exists (
      select 1
      from public.dkd_friend_requests dkd_request_row
      where dkd_request_row.requester_id = (select dkd_current_user_id from dkd_current_user_query)
        and dkd_request_row.addressee_id = dkd_profile_row.user_id
        and dkd_request_row.status = 'pending'
    ) as pending_sent,
    exists (
      select 1
      from public.dkd_friend_requests dkd_request_row
      where dkd_request_row.requester_id = dkd_profile_row.user_id
        and dkd_request_row.addressee_id = (select dkd_current_user_id from dkd_current_user_query)
        and dkd_request_row.status = 'pending'
    ) as pending_received,
    (
      select dkd_request_row.id
      from public.dkd_friend_requests dkd_request_row
      where dkd_request_row.requester_id = dkd_profile_row.user_id
        and dkd_request_row.addressee_id = (select dkd_current_user_id from dkd_current_user_query)
        and dkd_request_row.status = 'pending'
      order by dkd_request_row.created_at desc
      limit 1
    ) as request_id
  from public.dkd_profiles dkd_profile_row
  cross join dkd_current_user_query
  where dkd_current_user_query.dkd_current_user_id is not null
    and dkd_profile_row.user_id <> dkd_current_user_query.dkd_current_user_id
    and coalesce(trim(dkd_param_query), '') <> ''
    and public.dkd_social_is_blocked(dkd_current_user_query.dkd_current_user_id, dkd_profile_row.user_id) is false
    and (
      (dkd_current_user_query.dkd_digits_text <> '' and dkd_profile_row.ally_id::text = dkd_current_user_query.dkd_digits_text)
      or lower(coalesce(dkd_profile_row.nickname, '')) like ('%' || dkd_current_user_query.dkd_query_text || '%')
    )
  order by
    case when dkd_current_user_query.dkd_digits_text <> '' and dkd_profile_row.ally_id::text = dkd_current_user_query.dkd_digits_text then 0 else 1 end,
    case when lower(coalesce(dkd_profile_row.nickname, '')) = dkd_current_user_query.dkd_query_text then 0 else 1 end,
    dkd_profile_row.level desc,
    dkd_profile_row.updated_at desc
  limit greatest(1, least(coalesce(dkd_param_limit, 12), 20));
$$;

revoke all on function public.dkd_social_search_profiles(text, integer) from public;
grant execute on function public.dkd_social_search_profiles(text, integer) to authenticated;

create or replace function public.dkd_social_send_friend_request(dkd_param_target_user_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  dkd_current_user_id uuid := auth.uid();
  dkd_low_user_id uuid;
  dkd_high_user_id uuid;
  dkd_target_exists_value boolean := false;
  dkd_friendship_id_value bigint;
  dkd_request_id_value bigint;
begin
  if dkd_current_user_id is null then
    return jsonb_build_object('ok', false, 'reason', 'auth_required');
  end if;

  if dkd_param_target_user_id is null then
    return jsonb_build_object('ok', false, 'reason', 'target_not_found');
  end if;

  if dkd_param_target_user_id = dkd_current_user_id then
    return jsonb_build_object('ok', false, 'reason', 'cannot_friend_self');
  end if;

  select exists (
    select 1
    from public.dkd_profiles dkd_profile_row
    where dkd_profile_row.user_id = dkd_param_target_user_id
  ) into dkd_target_exists_value;

  if dkd_target_exists_value is not true then
    return jsonb_build_object('ok', false, 'reason', 'target_not_found');
  end if;

  insert into public.dkd_profiles (user_id) values (dkd_current_user_id) on conflict (user_id) do nothing;

  if public.dkd_social_is_blocked(dkd_current_user_id, dkd_param_target_user_id) then
    return jsonb_build_object('ok', false, 'reason', 'blocked_relationship');
  end if;

  dkd_low_user_id := case when dkd_current_user_id::text < dkd_param_target_user_id::text then dkd_current_user_id else dkd_param_target_user_id end;
  dkd_high_user_id := case when dkd_current_user_id::text < dkd_param_target_user_id::text then dkd_param_target_user_id else dkd_current_user_id end;

  select dkd_friendship_row.id into dkd_friendship_id_value
  from public.dkd_friendships dkd_friendship_row
  where dkd_friendship_row.user_low = dkd_low_user_id
    and dkd_friendship_row.user_high = dkd_high_user_id
  limit 1;

  if dkd_friendship_id_value is not null then
    return jsonb_build_object('ok', false, 'reason', 'friend_exists');
  end if;

  select dkd_request_row.id into dkd_request_id_value
  from public.dkd_friend_requests dkd_request_row
  where dkd_request_row.requester_id = dkd_param_target_user_id
    and dkd_request_row.addressee_id = dkd_current_user_id
    and dkd_request_row.status = 'pending'
  order by dkd_request_row.created_at desc
  limit 1;

  if dkd_request_id_value is not null then
    perform public.dkd_social_respond_friend_request(dkd_request_id_value, 'accept');
    return jsonb_build_object('ok', true, 'reason', 'accepted_existing');
  end if;

  select dkd_request_row.id into dkd_request_id_value
  from public.dkd_friend_requests dkd_request_row
  where dkd_request_row.requester_id = dkd_current_user_id
    and dkd_request_row.addressee_id = dkd_param_target_user_id
    and dkd_request_row.status = 'pending'
  order by dkd_request_row.created_at desc
  limit 1;

  if dkd_request_id_value is not null then
    return jsonb_build_object('ok', false, 'reason', 'request_exists');
  end if;

  insert into public.dkd_friend_requests (requester_id, addressee_id, status)
  values (dkd_current_user_id, dkd_param_target_user_id, 'pending');

  return jsonb_build_object('ok', true, 'reason', 'request_sent');
end;
$$;

revoke all on function public.dkd_social_send_friend_request(uuid) from public;
grant execute on function public.dkd_social_send_friend_request(uuid) to authenticated;

create or replace function public.dkd_social_respond_friend_request(dkd_param_request_id bigint, dkd_param_action text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  dkd_current_user_id uuid := auth.uid();
  dkd_request_row public.dkd_friend_requests%rowtype;
  dkd_low_user_id uuid;
  dkd_high_user_id uuid;
  dkd_friendship_id_value bigint;
  dkd_thread_id_value uuid;
  dkd_action_key text := lower(coalesce(trim(dkd_param_action), 'accept'));
begin
  if dkd_current_user_id is null then
    return jsonb_build_object('ok', false, 'reason', 'auth_required');
  end if;

  select * into dkd_request_row
  from public.dkd_friend_requests
  where id = dkd_param_request_id
  limit 1;

  if dkd_request_row.id is null then
    return jsonb_build_object('ok', false, 'reason', 'request_not_found');
  end if;

  if dkd_request_row.addressee_id <> dkd_current_user_id then
    return jsonb_build_object('ok', false, 'reason', 'not_request_target');
  end if;

  if dkd_request_row.status <> 'pending' then
    return jsonb_build_object('ok', false, 'reason', 'request_closed');
  end if;

  if dkd_action_key not in ('accept', 'reject') then
    return jsonb_build_object('ok', false, 'reason', 'invalid_action');
  end if;

  if dkd_action_key = 'accept' and public.dkd_social_is_blocked(dkd_current_user_id, dkd_request_row.requester_id) then
    update public.dkd_friend_requests
    set status = 'canceled',
        responded_at = now()
    where id = dkd_request_row.id;

    return jsonb_build_object('ok', false, 'reason', 'blocked_relationship');
  end if;

  update public.dkd_friend_requests
  set status = case when dkd_action_key = 'accept' then 'accepted' else 'rejected' end,
      responded_at = now()
  where id = dkd_request_row.id;

  if dkd_action_key = 'reject' then
    return jsonb_build_object('ok', true, 'reason', 'rejected');
  end if;

  dkd_low_user_id := case when dkd_request_row.requester_id::text < dkd_request_row.addressee_id::text then dkd_request_row.requester_id else dkd_request_row.addressee_id end;
  dkd_high_user_id := case when dkd_request_row.requester_id::text < dkd_request_row.addressee_id::text then dkd_request_row.addressee_id else dkd_request_row.requester_id end;

  insert into public.dkd_friendships (user_low, user_high, created_by)
  values (dkd_low_user_id, dkd_high_user_id, dkd_current_user_id)
  on conflict (user_low, user_high) do nothing;

  select id into dkd_friendship_id_value
  from public.dkd_friendships
  where user_low = dkd_low_user_id
    and user_high = dkd_high_user_id
  limit 1;

  insert into public.dkd_dm_threads (friendship_id, last_message_text, last_message_at)
  values (dkd_friendship_id_value, null, null)
  on conflict (friendship_id) do nothing;

  select id into dkd_thread_id_value
  from public.dkd_dm_threads
  where friendship_id = dkd_friendship_id_value
  limit 1;

  update public.dkd_friend_requests
  set status = 'canceled',
      responded_at = now()
  where requester_id = dkd_request_row.addressee_id
    and addressee_id = dkd_request_row.requester_id
    and status = 'pending';

  return jsonb_build_object('ok', true, 'reason', 'accepted', 'thread_id', dkd_thread_id_value);
end;
$$;

