-- DraBornGo Google Play UGC moderation guardrails - current safe baseline
-- Amaç: DM / sosyal / arkadaşlık akışına kullanıcı engelleme, kullanıcı/mesaj şikayeti,
-- admin moderasyon kuyruğu ve engellenen kullanıcıdan mesaj / arkadaşlık isteği kesme güvenliği ekler.

create table if not exists public.dkd_social_blocks (
  dkd_id bigint generated by default as identity primary key,
  dkd_blocker_user_id uuid not null references public.dkd_profiles(user_id) on delete cascade,
  dkd_blocked_user_id uuid not null references public.dkd_profiles(user_id) on delete cascade,
  dkd_reason_text text,
  dkd_created_at timestamptz not null default now(),
  constraint dkd_social_blocks_not_self check (dkd_blocker_user_id <> dkd_blocked_user_id)
);

create unique index if not exists dkd_social_blocks_pair_unique_idx
on public.dkd_social_blocks(dkd_blocker_user_id, dkd_blocked_user_id);

create index if not exists dkd_social_blocks_blocker_idx
on public.dkd_social_blocks(dkd_blocker_user_id, dkd_created_at desc);

create index if not exists dkd_social_blocks_blocked_idx
on public.dkd_social_blocks(dkd_blocked_user_id, dkd_created_at desc);

create table if not exists public.dkd_social_reports (
  dkd_id bigint generated by default as identity primary key,
  dkd_reporter_user_id uuid not null references public.dkd_profiles(user_id) on delete cascade,
  dkd_reported_user_id uuid not null references public.dkd_profiles(user_id) on delete cascade,
  dkd_thread_id uuid references public.dkd_dm_threads(id) on delete set null,
  dkd_message_id bigint references public.dkd_dm_messages(id) on delete set null,
  dkd_reason_key text not null default 'dkd_inappropriate_content',
  dkd_detail_text text,
  dkd_status_key text not null default 'dkd_open',
  dkd_admin_note_text text,
  dkd_admin_user_id uuid references public.dkd_profiles(user_id) on delete set null,
  dkd_created_at timestamptz not null default now(),
  dkd_updated_at timestamptz not null default now(),
  dkd_resolved_at timestamptz,
  constraint dkd_social_reports_not_self check (dkd_reporter_user_id <> dkd_reported_user_id),
  constraint dkd_social_reports_status_key_check check (dkd_status_key in ('dkd_open', 'dkd_reviewing', 'dkd_resolved', 'dkd_dismissed')),
  constraint dkd_social_reports_reason_key_check check (char_length(trim(dkd_reason_key)) between 3 and 80),
  constraint dkd_social_reports_detail_len_check check (dkd_detail_text is null or char_length(trim(dkd_detail_text)) <= 1200)
);

create index if not exists dkd_social_reports_status_idx
on public.dkd_social_reports(dkd_status_key, dkd_created_at desc);

create index if not exists dkd_social_reports_reporter_idx
on public.dkd_social_reports(dkd_reporter_user_id, dkd_created_at desc);

create index if not exists dkd_social_reports_reported_idx
on public.dkd_social_reports(dkd_reported_user_id, dkd_created_at desc);

alter table public.dkd_social_blocks enable row level security;
alter table public.dkd_social_reports enable row level security;

drop policy if exists dkd_social_blocks_select_guard on public.dkd_social_blocks;
create policy dkd_social_blocks_select_guard
on public.dkd_social_blocks
for select to authenticated
using (
  auth.uid() = dkd_blocker_user_id
  or auth.uid() = dkd_blocked_user_id
  or coalesce(public.dkd_is_admin(), false)
);

drop policy if exists dkd_social_reports_select_guard on public.dkd_social_reports;
create policy dkd_social_reports_select_guard
on public.dkd_social_reports
for select to authenticated
using (
  auth.uid() = dkd_reporter_user_id
  or coalesce(public.dkd_is_admin(), false)
);

drop policy if exists dkd_social_reports_update_admin_guard on public.dkd_social_reports;
create policy dkd_social_reports_update_admin_guard
on public.dkd_social_reports
for update to authenticated
using (coalesce(public.dkd_is_admin(), false))
with check (coalesce(public.dkd_is_admin(), false));
-- dkd_social_reports tablosu dkd_updated_at kolonunu RPC içinde manuel günceller; eski updated_at tetikleyicisi kullanılmaz.
drop trigger if exists dkd_social_reports_updated_at_trigger on public.dkd_social_reports;

create or replace function public.dkd_social_is_blocked(
  dkd_param_source_user_id uuid,
  dkd_param_target_user_id uuid
)
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1
    from public.dkd_social_blocks dkd_block_row
    where (
      dkd_block_row.dkd_blocker_user_id = dkd_param_source_user_id
      and dkd_block_row.dkd_blocked_user_id = dkd_param_target_user_id
    ) or (
      dkd_block_row.dkd_blocker_user_id = dkd_param_target_user_id
      and dkd_block_row.dkd_blocked_user_id = dkd_param_source_user_id
    )
  );
$$;

revoke all on function public.dkd_social_is_blocked(uuid, uuid) from public;
grant execute on function public.dkd_social_is_blocked(uuid, uuid) to authenticated, service_role;

create or replace function public.dkd_social_block_user(
  dkd_param_target_user_id uuid,
  dkd_param_reason_text text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  dkd_current_user_id uuid := auth.uid();
  dkd_target_exists_value boolean := false;
  dkd_low_user_id uuid;
  dkd_high_user_id uuid;
  dkd_removed_friendship_count integer := 0;
  dkd_closed_request_count integer := 0;
begin
  if dkd_current_user_id is null then
    return jsonb_build_object('ok', false, 'reason', 'auth_required');
  end if;

  if dkd_param_target_user_id is null then
    return jsonb_build_object('ok', false, 'reason', 'target_not_found');
  end if;

  if dkd_param_target_user_id = dkd_current_user_id then
    return jsonb_build_object('ok', false, 'reason', 'cannot_block_self');
  end if;

  select exists (
    select 1
    from public.dkd_profiles dkd_profile_row
    where dkd_profile_row.user_id = dkd_param_target_user_id
  ) into dkd_target_exists_value;

  if dkd_target_exists_value is not true then
    return jsonb_build_object('ok', false, 'reason', 'target_not_found');
  end if;

  insert into public.dkd_social_blocks (
    dkd_blocker_user_id,
    dkd_blocked_user_id,
    dkd_reason_text,
    dkd_created_at
  ) values (
    dkd_current_user_id,
    dkd_param_target_user_id,
    nullif(trim(coalesce(dkd_param_reason_text, '')), ''),
    now()
  )
  on conflict (dkd_blocker_user_id, dkd_blocked_user_id) do update
    set dkd_reason_text = excluded.dkd_reason_text,
        dkd_created_at = now();

  update public.dkd_friend_requests dkd_request_row
  set status = 'canceled',
      responded_at = now()
  where dkd_request_row.status = 'pending'
    and (
      (dkd_request_row.requester_id = dkd_current_user_id and dkd_request_row.addressee_id = dkd_param_target_user_id)
      or (dkd_request_row.requester_id = dkd_param_target_user_id and dkd_request_row.addressee_id = dkd_current_user_id)
    );

  get diagnostics dkd_closed_request_count = row_count;

  dkd_low_user_id := case when dkd_current_user_id::text < dkd_param_target_user_id::text then dkd_current_user_id else dkd_param_target_user_id end;
  dkd_high_user_id := case when dkd_current_user_id::text < dkd_param_target_user_id::text then dkd_param_target_user_id else dkd_current_user_id end;

  delete from public.dkd_friendships dkd_friendship_row
  where dkd_friendship_row.user_low = dkd_low_user_id
    and dkd_friendship_row.user_high = dkd_high_user_id;

  get diagnostics dkd_removed_friendship_count = row_count;

  return jsonb_build_object(
    'ok', true,
    'reason', 'blocked',
    'dkd_closed_request_count', dkd_closed_request_count,
    'dkd_removed_friendship_count', dkd_removed_friendship_count
  );
end;
$$;

revoke all on function public.dkd_social_block_user(uuid, text) from public;
grant execute on function public.dkd_social_block_user(uuid, text) to authenticated;

