create or replace function public.dkd_social_get_or_create_thread(dkd_param_friend_user_id uuid)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  dkd_current_user_id uuid := auth.uid();
  dkd_low_user_id uuid;
  dkd_high_user_id uuid;
  dkd_friendship_id_value bigint;
  dkd_thread_id_value uuid;
begin
  if dkd_current_user_id is null then
    raise exception 'auth_required';
  end if;

  if public.dkd_social_is_blocked(dkd_current_user_id, dkd_param_friend_user_id) then
    raise exception 'blocked_relationship';
  end if;

  dkd_low_user_id := case when dkd_current_user_id::text < dkd_param_friend_user_id::text then dkd_current_user_id else dkd_param_friend_user_id end;
  dkd_high_user_id := case when dkd_current_user_id::text < dkd_param_friend_user_id::text then dkd_param_friend_user_id else dkd_current_user_id end;

  select id into dkd_friendship_id_value
  from public.dkd_friendships
  where user_low = dkd_low_user_id
    and user_high = dkd_high_user_id
  limit 1;

  if dkd_friendship_id_value is null then
    raise exception 'friendship_not_found';
  end if;

  insert into public.dkd_dm_threads (friendship_id)
  values (dkd_friendship_id_value)
  on conflict (friendship_id) do nothing;

  select id into dkd_thread_id_value
  from public.dkd_dm_threads
  where friendship_id = dkd_friendship_id_value
  limit 1;

  return dkd_thread_id_value;
end;
$$;

