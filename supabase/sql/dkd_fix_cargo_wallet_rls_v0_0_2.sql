create or replace function public.dkd_cargo_shipments_for_me()
returns table (
  id bigint,
  customer_user_id uuid,
  customer_first_name text,
  customer_last_name text,
  customer_full_name text,
  customer_national_id text,
  customer_phone_text text,
  pickup_address_text text,
  delivery_address_text text,
  delivery_note text,
  pickup_lat numeric,
  pickup_lng numeric,
  dropoff_lat numeric,
  dropoff_lng numeric,
  courier_fee_tl numeric,
  customer_charge_tl numeric,
  payment_status text,
  paid_at timestamptz,
  package_content_text text,
  package_image_url text,
  pickup_proof_image_url text,
  package_weight_kg numeric,
  status text,
  created_at timestamptz,
  accepted_at timestamptz,
  picked_up_at timestamptz,
  completed_at timestamptz,
  courier_job_id bigint,
  assigned_courier_user_id uuid,
  courier_display_name text,
  courier_plate_no text,
  courier_vehicle_type text,
  courier_lat numeric,
  courier_lng numeric,
  courier_eta_min integer,
  courier_heading_deg numeric,
  courier_location_updated_at timestamptz
)
language sql
security definer
set search_path = public, auth
as $$
  select
    dkd_shipment_scope.id,
    dkd_shipment_scope.customer_user_id,
    coalesce(dkd_shipment_scope.customer_first_name, '') as customer_first_name,
    coalesce(dkd_shipment_scope.customer_last_name, '') as customer_last_name,
    trim(concat_ws(' ', dkd_shipment_scope.customer_first_name, dkd_shipment_scope.customer_last_name)) as customer_full_name,
    coalesce(dkd_shipment_scope.customer_national_id, '') as customer_national_id,
    coalesce(dkd_shipment_scope.customer_phone_text, '') as customer_phone_text,
    coalesce(dkd_shipment_scope.pickup_address_text, '') as pickup_address_text,
    coalesce(dkd_shipment_scope.delivery_address_text, '') as delivery_address_text,
    coalesce(dkd_shipment_scope.delivery_note, '') as delivery_note,
    dkd_shipment_scope.pickup_lat,
    dkd_shipment_scope.pickup_lng,
    dkd_shipment_scope.dropoff_lat,
    dkd_shipment_scope.dropoff_lng,
    coalesce(dkd_shipment_scope.courier_fee_tl, 0)::numeric as courier_fee_tl,
    coalesce(dkd_shipment_scope.customer_charge_tl, 0)::numeric as customer_charge_tl,
    coalesce(dkd_shipment_scope.payment_status, '') as payment_status,
    dkd_shipment_scope.paid_at,
    coalesce(dkd_shipment_scope.package_content_text, '') as package_content_text,
    coalesce(dkd_shipment_scope.package_image_url, '') as package_image_url,
    coalesce(dkd_shipment_scope.pickup_proof_image_url, '') as pickup_proof_image_url,
    coalesce(dkd_shipment_scope.package_weight_kg, 0)::numeric as package_weight_kg,
    coalesce(dkd_shipment_scope.status, 'open') as status,
    dkd_shipment_scope.created_at,
    dkd_shipment_scope.accepted_at,
    dkd_shipment_scope.picked_up_at,
    dkd_shipment_scope.completed_at,
    dkd_shipment_scope.courier_job_id,
    dkd_shipment_scope.assigned_courier_user_id,
    coalesce(dkd_profile_scope.nickname, 'Kurye atandı') as courier_display_name,
    coalesce(dkd_live_scope.plate_no, dkd_shipment_scope.assigned_courier_plate_no, '') as courier_plate_no,
    coalesce(dkd_live_scope.vehicle_type, dkd_shipment_scope.assigned_courier_vehicle_type, dkd_profile_scope.courier_vehicle_type, '') as courier_vehicle_type,
    dkd_live_scope.lat as courier_lat,
    dkd_live_scope.lng as courier_lng,
    coalesce(dkd_live_scope.eta_min, dkd_shipment_scope.courier_eta_min) as courier_eta_min,
    dkd_live_scope.heading_deg as courier_heading_deg,
    dkd_live_scope.updated_at as courier_location_updated_at
  from public.dkd_cargo_shipments dkd_shipment_scope
  left join public.dkd_profiles dkd_profile_scope
    on dkd_profile_scope.user_id = dkd_shipment_scope.assigned_courier_user_id
  left join public.dkd_courier_live_locations dkd_live_scope
    on dkd_live_scope.courier_user_id = dkd_shipment_scope.assigned_courier_user_id
  where dkd_shipment_scope.customer_user_id = auth.uid()
     or dkd_shipment_scope.assigned_courier_user_id = auth.uid()
  order by dkd_shipment_scope.created_at desc nulls last, dkd_shipment_scope.id desc
  limit 50;
$$;

