create or replace function public.dkd_cargo_shipment_create(
  dkd_param_customer_first_name text,
  dkd_param_customer_last_name text,
  dkd_param_customer_national_id text,
  dkd_param_customer_phone_text text,
  dkd_param_pickup_address_text text,
  dkd_param_delivery_address_text text,
  dkd_param_delivery_note_text text,
  dkd_param_package_content_text text,
  dkd_param_package_image_url text,
  dkd_param_package_weight_kg numeric,
  dkd_param_pickup_lat numeric,
  dkd_param_pickup_lng numeric,
  dkd_param_dropoff_lat numeric,
  dkd_param_dropoff_lng numeric,
  dkd_param_pickup_distance_km numeric,
  dkd_param_delivery_distance_km numeric,
  dkd_param_courier_fee_tl numeric,
  dkd_param_customer_charge_tl numeric
)
returns jsonb
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  dkd_user_id_value uuid := auth.uid();
  dkd_wallet_before_tl_value numeric(12,2) := 0;
  dkd_wallet_after_tl_value numeric(12,2) := 0;
  dkd_shipment_id_value bigint := null;
  dkd_courier_job_id_value bigint := null;
  dkd_distance_km_value numeric(12,2) := 0;
  dkd_eta_min_value integer := 15;
  dkd_customer_name_value text := '';
  dkd_package_title_value text := '';
  dkd_cargo_meta_value jsonb := '{}'::jsonb;
begin
  if dkd_user_id_value is null then
    raise exception 'dkd_auth_required';
  end if;

  if coalesce(dkd_param_customer_charge_tl, 0) <= 0 then
    raise exception 'dkd_cargo_payment_amount_required';
  end if;

  insert into public.dkd_profiles (user_id)
  values (dkd_user_id_value)
  on conflict (user_id) do nothing;

  select round(coalesce(dkd_profile_scope.wallet_tl, 0)::numeric, 2)
  into dkd_wallet_before_tl_value
  from public.dkd_profiles dkd_profile_scope
  where dkd_profile_scope.user_id = dkd_user_id_value
  for update;

  if coalesce(dkd_wallet_before_tl_value, 0) < round(coalesce(dkd_param_customer_charge_tl, 0)::numeric, 2) then
    raise exception 'wallet_insufficient';
  end if;

  update public.dkd_profiles
  set wallet_tl = round(greatest(coalesce(wallet_tl, 0) - coalesce(dkd_param_customer_charge_tl, 0), 0)::numeric, 2)
  where user_id = dkd_user_id_value
  returning round(coalesce(wallet_tl, 0)::numeric, 2)
  into dkd_wallet_after_tl_value;

  dkd_distance_km_value := round(greatest(coalesce(dkd_param_pickup_distance_km, 0), 0) + greatest(coalesce(dkd_param_delivery_distance_km, 0), 0), 2);
  dkd_eta_min_value := greatest(12, least(180, (ceil(greatest(coalesce(dkd_distance_km_value, 1), 1) * 6) + 8)::integer));
  dkd_customer_name_value := trim(concat_ws(' ', nullif(trim(coalesce(dkd_param_customer_first_name, '')), ''), nullif(trim(coalesce(dkd_param_customer_last_name, '')), '')));
  dkd_package_title_value := coalesce(nullif(trim(coalesce(dkd_param_package_content_text, '')), ''), 'Paket');

  insert into public.dkd_cargo_shipments (
    customer_user_id,
    customer_first_name,
    customer_last_name,
    customer_national_id,
    customer_phone_text,
    pickup_address_text,
    delivery_address_text,
    delivery_note,
    pickup_lat,
    pickup_lng,
    dropoff_lat,
    dropoff_lng,
    pickup_distance_km,
    delivery_distance_km,
    courier_fee_tl,
    customer_charge_tl,
    payment_status,
    paid_at,
    package_content_text,
    package_image_url,
    package_weight_kg,
    status
  ) values (
    dkd_user_id_value,
    nullif(trim(coalesce(dkd_param_customer_first_name, '')), ''),
    nullif(trim(coalesce(dkd_param_customer_last_name, '')), ''),
    nullif(regexp_replace(coalesce(dkd_param_customer_national_id, ''), '[^0-9]', '', 'g'), ''),
    nullif(trim(coalesce(dkd_param_customer_phone_text, '')), ''),
    nullif(trim(coalesce(dkd_param_pickup_address_text, '')), ''),
    nullif(trim(coalesce(dkd_param_delivery_address_text, '')), ''),
    coalesce(nullif(trim(coalesce(dkd_param_delivery_note_text, '')), ''), 'Teşekkür Ederim'),
    dkd_param_pickup_lat,
    dkd_param_pickup_lng,
    dkd_param_dropoff_lat,
    dkd_param_dropoff_lng,
    round(greatest(coalesce(dkd_param_pickup_distance_km, 0), 0)::numeric, 2),
    round(greatest(coalesce(dkd_param_delivery_distance_km, 0), 0)::numeric, 2),
    round(greatest(coalesce(dkd_param_courier_fee_tl, 0), 0)::numeric, 2),
    round(greatest(coalesce(dkd_param_customer_charge_tl, 0), 0)::numeric, 2),
    'paid',
    now(),
    dkd_package_title_value,
    nullif(trim(coalesce(dkd_param_package_image_url, '')), ''),
    round(greatest(coalesce(dkd_param_package_weight_kg, 1), 0.1)::numeric, 2),
    'open'
  )
  returning id into dkd_shipment_id_value;

  dkd_cargo_meta_value := jsonb_build_object(
    'dkd_source', 'dkd_cargo_sender_panel_wallet_payment',
    'dkd_cargo_shipment_id', dkd_shipment_id_value,
    'dkd_customer_user_id', dkd_user_id_value,
    'dkd_customer_name', dkd_customer_name_value,
    'dkd_phone_text', dkd_param_customer_phone_text,
    'dkd_package_content_text', dkd_package_title_value,
    'dkd_package_image_url', dkd_param_package_image_url,
    'dkd_package_weight_kg', dkd_param_package_weight_kg,
    'dkd_pickup_address_text', dkd_param_pickup_address_text,
    'dkd_delivery_address_text', dkd_param_delivery_address_text,
    'dkd_delivery_note_text', coalesce(nullif(trim(coalesce(dkd_param_delivery_note_text, '')), ''), 'Teşekkür Ederim'),
    'dkd_customer_charge_tl', round(greatest(coalesce(dkd_param_customer_charge_tl, 0), 0)::numeric, 2),
    'dkd_wallet_before_tl', dkd_wallet_before_tl_value,
    'dkd_wallet_after_tl', dkd_wallet_after_tl_value
  );

  insert into public.dkd_courier_jobs (
    title,
    pickup,
    dropoff,
    reward_score,
    distance_km,
    eta_min,
    job_type,
    is_active,
    status,
    assigned_user_id,
    customer_user_id,
    delivery_address_text,
    delivery_note,
    fee_tl,
    customer_charge_tl,
    cargo_meta,
    cargo_shipment_id,
    pickup_status,
    pickup_lat,
    pickup_lng,
    dropoff_lat,
    dropoff_lng,
    merchant_name,
    product_title
  ) values (
    case when lower(dkd_package_title_value) like '%sipariş%' then dkd_package_title_value else dkd_package_title_value || ' Siparişi' end,
    coalesce(nullif(trim(coalesce(dkd_param_pickup_address_text, '')), ''), 'Gönderici adresi'),
    coalesce(nullif(trim(coalesce(dkd_param_delivery_address_text, '')), ''), 'Teslimat adresi'),
    16,
    greatest(coalesce(dkd_distance_km_value, 1), 1),
    dkd_eta_min_value,
    'cargo',
    true,
    'open',
    null,
    dkd_user_id_value,
    nullif(trim(coalesce(dkd_param_delivery_address_text, '')), ''),
    coalesce(nullif(trim(coalesce(dkd_param_delivery_note_text, '')), ''), 'Teşekkür Ederim'),
    round(greatest(coalesce(dkd_param_courier_fee_tl, 0), 0)::numeric, 2),
    round(greatest(coalesce(dkd_param_customer_charge_tl, 0), 0)::numeric, 2),
    dkd_cargo_meta_value,
    dkd_shipment_id_value,
    'pending',
    dkd_param_pickup_lat,
    dkd_param_pickup_lng,
    dkd_param_dropoff_lat,
    dkd_param_dropoff_lng,
    'Gönderi Paneli',
    dkd_package_title_value
  ) returning id into dkd_courier_job_id_value;

  update public.dkd_cargo_shipments
  set courier_job_id = dkd_courier_job_id_value,
      updated_at = now()
  where id = dkd_shipment_id_value;

  return jsonb_build_object(
    'ok', true,
    'dkd_ok_value', true,
    'id', dkd_shipment_id_value,
    'cargo_shipment_id', dkd_shipment_id_value,
    'dkd_cargo_shipment_id', dkd_shipment_id_value,
    'courier_job_id', dkd_courier_job_id_value,
    'dkd_courier_job_id', dkd_courier_job_id_value,
    'wallet_tl', dkd_wallet_after_tl_value,
    'dkd_wallet_before_tl', dkd_wallet_before_tl_value,
    'dkd_wallet_after_tl', dkd_wallet_after_tl_value,
    'payment_status', 'paid',
    'status', 'open'
  );
end;
$$;

